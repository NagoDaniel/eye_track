def test_pages_list_detail_edit_delete(admin: Admin, clips: Clips) -> None:
    c = admin.client
    page = c.get("/admin/videos")
    assert page.status_code == 200 and "<script" not in page.text
    assert (
        'enctype="multipart/form-data"' in page.text and 'action="/admin/api/videos"' in page.text
    )
    token = csrf_from(page.text)

    v = upload(admin, clips.cfr, title="Page test").json()
    assert "Page test" in c.get("/admin/videos").text
    detail = c.get(f"/admin/videos/{v['id']}")
    assert detail.status_code == 200
    for expected in (v["sha256"], "25.000 fps", "160x120", str(v["size_bytes"]), "Page test"):
        assert expected in detail.text

    url = f"/admin/videos/{v['id']}"
    aois = '{"aois": []}'
    assert c.post(url, data={"title": "x", "aois": aois, "csrf_token": "bad"}).status_code == 403
    r = c.post(url, data={"title": "Edited", "aois": aois, "csrf_token": token})
    assert r.status_code == 303 and r.headers["location"] == f"{url}?saved=true"
    assert "Edited" in c.get(r.headers["location"]).text
    assert json.loads((admin.data_root / "videos" / str(v["id"]) / "aois.json").read_text()) == {
        "aois": []
    }
    bad = c.post(url, data={"title": "Edited", "aois": "[1]", "csrf_token": token})
    assert bad.status_code == 422 and "aois must be a JSON object" in bad.text

    assert c.post(f"{url}/delete", data={"csrf_token": "bad"}).status_code == 403
    study_with_playlist(admin, "page1", [str(v["id"])])
    r = c.post(f"{url}/delete", data={"csrf_token": token})
    assert r.status_code == 409 and "page1" in r.text
    c.delete("/admin/api/studies/1", headers=admin.headers)
    r = c.post(f"{url}/delete", data={"csrf_token": token})
    assert r.status_code == 303 and r.headers["location"] == "/admin/videos"
    assert c.get(url).status_code == 404
