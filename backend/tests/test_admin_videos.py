    assert r.status_code == 303
    location = r.headers["location"]
    assert location.startswith("/admin/videos/") and "warn=" in location
    page = admin.client.get(location)
    assert "Warning: video codec is mpeg4" in page.text
    assert "Warning:" not in admin.client.get(location.split("?")[0]).text  # shown once


