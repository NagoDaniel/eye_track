def test_cfr_upload_stores_file_and_metadata(admin: Admin, clips: Clips) -> None:
    r = upload(admin, clips.cfr, title="  Intro  ")
    assert r.status_code == 201, r.text
    v = r.json()
    assert v["title"] == "Intro"
    assert (v["width"], v["height"], v["fps"]) == (160, 120, 25.0)
    assert v["duration"] == pytest.approx(2.0, abs=0.1)
    assert v["warnings"] == []
    expected = hashlib.sha256(clips.cfr.read_bytes()).hexdigest()
    assert v["sha256"] == expected
    assert v["file_path"] == f"videos/{v['id']}/video.mp4"
    stored = admin.data_root / v["file_path"]
    assert stored.read_bytes() == clips.cfr.read_bytes()
    assert v["size_bytes"] == stored.stat().st_size
    assert [p.name for p in files_under(admin.data_root)] == ["video.mp4"]  # no temp files left

    assert admin.client.get(f"{URL}/{v['id']}").json() == {k: v[k] for k in v if k != "warnings"}
    assert [x["id"] for x in admin.client.get(URL).json()] == [v["id"]]


