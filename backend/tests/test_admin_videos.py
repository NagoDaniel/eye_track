URL = "/admin/api/videos"
LAVFI = ["-f", "lavfi", "-i", "testsrc=duration=2:size=160x120:rate=25"]
H264 = ["-c:v", "libx264", "-pix_fmt", "yuv420p"]


def ffmpeg(out: Path, *args: str) -> Path:
    assert shutil.which("ffmpeg") and shutil.which("ffprobe"), (
        "ffmpeg and ffprobe must be installed"
    )
    subprocess.run(
        ["ffmpeg", "-loglevel", "error", "-y", *args, str(out)], check=True, capture_output=True
    )
    return out


@dataclass(frozen=True)
class Clips:
    cfr: Path
    vfr: Path
    mpeg4: Path
    text: Path
    audio: Path


@pytest.fixture(scope="session")
def clips(tmp_path_factory: pytest.TempPathFactory) -> Clips:
    d = tmp_path_factory.mktemp("clips")
    text = d / "notes.mp4"
    text.write_text("this is not a video\n")
    return Clips(
        cfr=ffmpeg(d / "cfr.mp4", *LAVFI, *H264),
        # Dropping frames while keeping their timestamps gives a variable frame rate.
        vfr=ffmpeg(
            d / "vfr.mp4", *LAVFI, "-vf", r"select=gt(mod(n\,5)\,1)", "-fps_mode", "vfr", *H264
        ),
        mpeg4=ffmpeg(d / "mpeg4.mp4", *LAVFI, "-c:v", "mpeg4"),
        text=text,
        audio=ffmpeg(d / "audio.mp4", "-f", "lavfi", "-i", "sine=duration=1", "-c:a", "aac"),
    )


@pytest.fixture
def data_root(tmp_path: Path) -> Path:
    return tmp_path / "data"


@pytest.fixture
def admin(migrated_engine: Engine, data_root: Path) -> Generator[Admin]:
    with logged_in_admin(migrated_engine, data_root) as a:
        yield a


def upload(
    admin: Admin,
    path: Path,
    title: str = "Lecture",
    *,
    csrf: str | None = None,
    headers: dict[str, str] | None = None,
) -> Response:
    data = {"title": title, "csrf_token": admin.csrf if csrf is None else csrf}
    with path.open("rb") as f:
        return admin.client.post(
            URL, data=data, files={"file": (path.name, f, "video/mp4")}, headers=headers
        )


def files_under(root: Path) -> list[Path]:
    return [p for p in root.rglob("*") if p.is_file()] if root.exists() else []


def video_count(engine: Engine) -> int:
    with DbSession(engine) as db:
        return db.scalar(select(func.count()).select_from(Video)) or 0


